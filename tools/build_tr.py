#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Türkçe iʿrāb ödevleri (/odev/).

    python3 tools/build_tr.py            # build dist/odev/ only (build_site.py also calls build())
    python3 tools/build_tr.py --sql      # print the SQL that loads the answer keys into Supabase

Source: content/tr/irab<k>.json (format: content/tr/SPEC.md). The static lesson files never contain
answers; keys live only in the Supabase table tr_keys (students read a key after the teacher opens it).
"""
import glob, hashlib, json, os, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "content", "tr")
SITE = os.path.join(ROOT, "site", "odev")

KB = ["isim", "alem (özel isim)", "mastar", "ismi fail", "ismi mefûl", "ismi işaret", "ismi mevsul", "soru ismi",
      "munfasıl zamir", "muttasıl zamir", "gizli zamir", "mazi fiil", "muzari fiil", "emir fiil", "harfi cer", "atıf harfi",
      "inne ve benzerleri", "olumsuzluk edatı", "cezm edatı", "nasb edatı", "soru harfi", "diğer harf/edat"]
G = ["mübteda", "haber", "fiil", "fail", "naibi fail", "mefûlün bih", "mefûlün mutlak", "mefûlün fîh (zarf)", "hal", "sıfat",
     "muzafun ileyh", "mecrur (harfi cerden sonra)", "ma'tuf", "bedel", "innenin ismi", "innenin haberi", "nakıs fiil (kâne vb.)",
     "kânenin ismi", "kânenin haberi", "münada", "temyiz", "görevi yok (harf)"]
I = ["merfu", "mansub", "mecrur", "meczum", "mebni"]

def lst(v): return v if isinstance(v, list) else [v]

def lessons():
    out = []
    for f in glob.glob(os.path.join(SRC, "irab*.json")):
        d = json.load(open(f, encoding="utf-8"))
        d["id"] = f"tr-irab{d['irab']}"
        for it in d["items"]:
            for w in it["words"]:
                for p in w["parts"]:
                    for k, opts in (("kb", KB), ("g", G), ("i", I)):
                        for v in lst(p[k]):
                            if v not in opts: sys.exit(f"{f}: #{it['n']} '{p['t']}' {k}='{v}' is not an option")
        out.append(d)
    return sorted(out, key=lambda d: d["irab"])

def public(d):
    """Lesson as students load it: text only, no answers."""
    return {"id": d["id"], "irab": d["irab"], "calisma": d["calisma"], "title": d["title"],
            "items": [{"n": it["n"], "ref": it["ref"], "tr": it.get("tr", ""),
                       "words": [[{"t": p["t"], **({"h": 1} if p.get("hidden") else {})} for p in w["parts"]] for w in it["words"]]}
                      for it in d["items"]]}

def key(d):
    """[item][part] -> [kb, g, i], each a list of accepted answers."""
    return [[[lst(p["kb"]), lst(p["g"]), lst(p["i"])] for w in it["words"] for p in w["parts"]] for it in d["items"]]

def build(dist):
    out = os.path.join(dist, "odev")
    if os.path.isdir(out): shutil.rmtree(out)
    shutil.copytree(SITE, out)
    os.makedirs(os.path.join(out, "data"), exist_ok=True)
    man = []
    for d in lessons():
        raw = json.dumps(public(d), ensure_ascii=False, separators=(",", ":"))
        v = hashlib.sha1(raw.encode()).hexdigest()[:10]
        open(os.path.join(out, "data", d["id"] + ".json"), "w", encoding="utf-8").write(raw)
        man.append({"id": d["id"], "irab": d["irab"], "calisma": d["calisma"], "title": d["title"], "n": len(d["items"]),
                    "cells": sum(len(w["parts"]) for it in d["items"] for w in it["words"]) * 3, "v": v})
    json.dump({"lessons": man, "options": {"kb": KB, "g": G, "i": I}},
              open(os.path.join(out, "data", "manifest.json"), "w", encoding="utf-8"), ensure_ascii=False)
    cfg = os.path.join(dist, "config.js")
    if os.path.exists(cfg): shutil.copy(cfg, os.path.join(out, "config.js"))
    ver = hashlib.sha1(json.dumps(man).encode() + open(os.path.join(SITE, "app.js"), "rb").read()
                       + open(os.path.join(SITE, "style.css"), "rb").read()).hexdigest()[:10]
    page = open(os.path.join(SITE, "index.html"), encoding="utf-8").read().replace("__V__", ver)
    open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(page)
    with open(os.path.join(dist, "_headers"), "a") as h:
        h.write("/odev/data/*\n  Cache-Control: no-cache\n/odev/index.html\n  Cache-Control: no-cache\n/odev/config.js\n  Cache-Control: no-cache\n")
    print(f"Built dist/odev/: {len(man)} lessons, {sum(m['n'] for m in man)} items")

def sql():
    rows = []
    for d in lessons():
        k = json.dumps(key(d), ensure_ascii=False).replace("'", "''")
        rows.append(f"insert into public.tr_keys (lesson, key) values ('{d['id']}', '{k}'::jsonb)\n"
                    f"  on conflict (lesson) do update set key = excluded.key, updated_at = now();")
    return "-- Generated by tools/build_tr.py --sql. Re-running keeps each lesson's released flag.\n" + "\n".join(rows) + "\n"

if __name__ == "__main__":
    if "--sql" in sys.argv: sys.stdout.write(sql())
    else: build(os.path.join(ROOT, "dist"))
